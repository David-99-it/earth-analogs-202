class Command(BaseCommand):
    help = "Импорт земных аналогов из таблицы (обновляет по названию RU)"

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear", action="store_true", help="Удалить все записи перед импортом"
        )

    def handle(self, *args, **options):
        if options["clear"]:
            EarthAnalog.objects.all().delete()
        created = updated = 0
        for d in DATA:
            g, rel, tmp, wat, dust, cav, life = d["scores"]
            _, is_new = EarthAnalog.objects.update_or_create(
                name_ru=d["name_ru"],
                defaults=dict(
                    name_en=d["name_en"],
                    latitude=d["latitude"],
                    longitude=d["longitude"],
                    score_geology=g,
                    score_relief=rel,
                    score_temperature=tmp,
                    score_water_ice=wat,
                    score_dust_wind=dust,
                    score_caves=cav,
                    score_life=life,
                    is_unexplored=d["is_unexplored"],
                    fit_ru=d["fit_ru"],
                    fit_en=d["fit_en"],
                    break_ru=d["break_ru"],
                    break_en=d["break_en"],
                ),
            )
            created += is_new
            updated += not is_new
        self.stdout.write(
            self.style.SUCCESS(f"Готово: создано {created}, обновлено {updated}")
        )
